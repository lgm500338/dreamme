/** Pick the string for the current language (Korean, English, Spanish). */
export function pick<T>(lang: Language, ko: T, en: T, es: T): T {
  return lang === 'ko' ? ko : lang === 'es' ? es : en;
}

/** Locale for dates in the current language. */
export function localeFor(lang: Language) {
  return pick(lang, 'ko-KR', 'en-US', 'es-ES');
}

